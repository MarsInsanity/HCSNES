#!/usr/bin/env python3
"""Generate dispatch from the existing authoritative 1024-entry opcode table."""
import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]

def generate():
    source = (ROOT / 'source/fxinst.c').read_text()
    table = source.split('void (*fx_apfOpcodeTable[])(void) =', 1)[1]
    table = table.split('};', 1)[0]
    names = re.findall(r'&(fx_[a-zA-Z0-9_]+)', table)
    if len(names) != 1024:
        raise SystemExit('Expected exactly 1024 opcode entries')
    for index in (0x04c, 0x24c):
        names[index] = 'hcsnes_plot'
    for index in (0x14c, 0x34c):
        names[index] = 'hcsnes_rpix'
    out = ['/* Generated by tools/gen_fx_dispatch.py; do not edit. */',
           'static void *const dispatch[1024] = {']
    for i in range(0, 1024, 8):
        out.append('   ' + ', '.join('&&op_' + n for n in names[i:i+8]) + ',')
    out.extend(['};', 'HCSNES_DISPATCH();'])
    for name in dict.fromkeys(names):
        out.append('op_' + name + ':')
        call = 'GSU.pfPlot' if name == 'hcsnes_plot' else 'GSU.pfRpix' if name == 'hcsnes_rpix' else name
        out.extend(['   ' + call + '();', '   HCSNES_DISPATCH();'])
    return '\n'.join(out) + '\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'source/hcsnes_fx_dispatch.h'
    content = generate()
    if args.check:
        if output.read_text() != content:
            raise SystemExit('Dispatch header is stale')
        print('Dispatch: 1024 opcode entries verified')
    else:
        output.write_text(content, newline='\n')
